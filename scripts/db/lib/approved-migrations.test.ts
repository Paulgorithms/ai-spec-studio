function judge(files: MigrationFiles) {
  const results: CheckResult[] = [];
  const ok = checkMigrationFiles(files, (pass, label, detail) =>
    results.push(
      detail === undefined ? { pass, label } : { pass, label, detail },
    ),
  );
  return { ok, results, failed: results.filter((r) => !r.pass) };
}

describe("the approved migration list", () => {
  test("is 0000_initial_schema then 0001_auth_tables, with the approved hashes", () => {
    expect(
      APPROVED_MIGRATIONS.map((m) => [
        m.tag,
        m.when,
        m.sha256,
        m.snapshot.sha256,
      ]),
    ).toEqual([
      [
        "0000_initial_schema",
        1794739919891,
        "cb836c11552e8658df70d3366b9a26c4bb8c31e3fc82156a085216eae292eaf3",
        "29a486b353e5e25a9e96aa1529602e30b6570da4b52f019da4a87b7428fa47d1",
      ],
      [
        "0001_auth_tables",
        1795337179333,
        "75ae637faf83a71863593ffc1e6baba8e96239ee2d6234c9f6bd78fa4179afbb",
        "098736ea611ca8c49c6f713a27984c76eea4428f35eb38c9d432aef2b4081100",
      ],
    ]);
  });

  test("is ordered: numbered tags, strictly increasing timestamps, one snapshot chain", () => {
    APPROVED_MIGRATIONS.forEach((m, i) => {
      expect(m.tag.slice(0, 4)).toBe(String(i).padStart(4, "0"));
      expect(m.snapshot.file).toBe(`meta/${m.tag.slice(0, 4)}_snapshot.json`);
      const previous = APPROVED_MIGRATIONS[i - 1];
      if (previous) {
        expect(m.when).toBeGreaterThan(previous.when);
        expect(m.snapshot.prevId).toBe(previous.snapshot.id);
      } else {
        expect(m.snapshot.prevId).toBe(FIRST_SNAPSHOT_PREV_ID);
      }
    });
    expect(new Set(APPROVED_MIGRATIONS.map((m) => m.tag)).size).toBe(
      APPROVED_MIGRATIONS.length,
    );
  });

  test("the files on disk are exactly the approved ones", () => {
    const files = readMigrationFiles();
    expect(files.listing).toEqual(EXPECTED_LISTING);
    expect(judge(files).failed).toEqual([]);
  });

  test("the hashes are of the files on disk, computed like the migrator", () => {
    for (const m of APPROVED_MIGRATIONS) {
      const sql = readFileSync(`drizzle/${m.tag}.sql`, "utf8");
      expect(createHash("sha256").update(sql).digest("hex")).toBe(m.sha256);
    }
  });
});

// The expected catalog is written by hand; these tests hold it to the
// approved snapshots (generated by Drizzle Kit from the schema and reviewed).
describe("the expected structure matches the approved snapshots", () => {
  type SnapshotTable = {
    columns: Record<
      string,
      { name: string; type: string; notNull: boolean; default?: unknown }
    >;
    indexes: Record<
      string,
      {
        method: string;
        isUnique: boolean;
        columns: Array<{ expression: string; asc: boolean }>;
      }
    >;
    foreignKeys: Record<
      string,
      {
        tableTo: string;
        columnsFrom: string[];
        columnsTo: string[];
        onDelete: string;
        onUpdate: string;
      }
    >;
    uniqueConstraints: Record<
      string,
      { columns: string[]; nullsNotDistinct: boolean }
    >;
    checkConstraints: Record<string, { value: string }>;
    isRLSEnabled: boolean;
  };

  APPROVED_MIGRATIONS.forEach((migration, i) => {
    const snapshot = JSON.parse(
      readFileSync(`drizzle/${migration.snapshot.file}`, "utf8"),
    ) as { tables: Record<string, SnapshotTable> };
    const structure = expectedStructure(i + 1);
    const tables = Object.entries(snapshot.tables).map(([key, table]) => ({
      name: key.replace(/^public\./, ""),
      table,
    }));

    test(`${migration.tag}: the same tables, without row-level security`, () => {
      expect(tables.map((t) => t.name).sort()).toEqual(structure.tables);
      expect(tables.every((t) => !t.table.isRLSEnabled)).toBe(true);
    });

    test(`${migration.tag}: the same columns, in order, with type, nullability, and default`, () => {
      const pgType = (type: string) =>
        type.replace("timestamp (3)", "timestamp(3)");
      const pgDefault = (value: unknown) =>
        value === undefined
          ? null
          : typeof value === "string" && value.startsWith("'")
            ? `${value}::text`
            : String(value);
      const fromSnapshot = tables
        .sort((a, b) => (a.name < b.name ? -1 : 1))
        .flatMap(({ name, table }) =>
          Object.values(table.columns).map((c) => [
            name,
            c.name,
            pgType(c.type),
            c.notNull ? "NO" : "YES",
            pgDefault(c.default),
          ]),
        );
      expect(fromSnapshot).toEqual(structure.columns);
    });

    test(`${migration.tag}: the same UNIQUE, foreign key, and CHECK constraints`, () => {
      const names = (type: string) =>
        structure.constraints
          .filter((c) => c[2] === type)
          .map(([table, name]) => `${table}.${name}`)
          .sort();
      const snapshotNames = (
        pick: (t: SnapshotTable) => Record<string, unknown>,
      ) =>
        tables
          .flatMap(({ name, table }) =>
            Object.keys(pick(table)).map((key) => `${name}.${key}`),
          )
          .sort();
      expect(names("u")).toEqual(snapshotNames((t) => t.uniqueConstraints));
      expect(names("f")).toEqual(snapshotNames((t) => t.foreignKeys));
      expect(names("c")).toEqual(snapshotNames((t) => t.checkConstraints));
      expect(names("p")).toEqual(
        structure.tables.map((t) => `${t}.${t}_pkey`).sort(),
      );
    });

    test(`${migration.tag}: exact definitions agree with the snapshot`, () => {
      for (const { name: table, table: t } of tables) {
        for (const [name, fk] of Object.entries(t.foreignKeys)) {
          const spec = structure.constraints.find((c) => c[1] === name)!;
          const action = fk.onDelete.toUpperCase();
          expect(fk.onUpdate).toBe("no action");
          expect(spec[3].join(" ")).toContain(
            `FOREIGN KEY (${fk.columnsFrom.join(", ")}) REFERENCES ${fk.tableTo}(${fk.columnsTo.join(", ")}) ON DELETE ${action}`,
          );
        }
        for (const [name, unique] of Object.entries(t.uniqueConstraints)) {
          const spec = structure.constraints.find((c) => c[1] === name)!;
          expect(unique.nullsNotDistinct).toBe(false);
          expect(spec[3].join(" ")).toContain(
            `UNIQUE (${unique.columns.join(", ")})`,
          );
        }
        for (const [name, index] of Object.entries(t.indexes)) {
          const spec = structure.indexes.find((x) => x[1] === name)!;
          expect(spec[0]).toBe(table);
          expect(index.isUnique).toBe(false);
          const columns = index.columns
            .map((c) => `${c.expression}${c.asc ? "" : " DESC NULLS LAST"}`)
            .join(", ");
          expect(spec[2]).toContain(`USING ${index.method} (${columns})`);
        }
      }
    });
  });

  test("the auth CHECK is exactly the reviewed password IS NULL", () => {
    const snapshot = JSON.parse(
      readFileSync("drizzle/meta/0001_snapshot.json", "utf8"),
    ) as { tables: Record<string, SnapshotTable> };
    expect(
      snapshot.tables["public.accounts"]?.checkConstraints
        .accounts_password_null_check?.value,
    ).toBe('"accounts"."password" IS NULL');
    const spec = expectedStructure(2).constraints.find(
      (c) => c[1] === "accounts_password_null_check",
    );
    expect(spec).toEqual([
      "accounts",
      "accounts_password_null_check",
      "c",
      ["CHECK ((password IS NULL))"],
      "exact",
    ]);
  });
});

describe("expectedStructure", () => {
  // The rules reviewed for 0000_initial_schema (Step 4B), unchanged.
  test("after 0000 is exactly the original two tables' structure", () => {
    const s = expectedStructure(1);
    expect(s.tables).toEqual(["projects", "specifications"]);
    expect(s.columns).toHaveLength(14);
    expect(s.notNullColumns).toHaveLength(14);
    expect(
      s.constraints.map(([t, n, type, fragments]) => [t, n, type, fragments]),
    ).toEqual([
      ["projects", "projects_pkey", "p", ["PRIMARY KEY (id)"]],
      [
        "projects",
        "projects_slug_format_check",
        "c",
        [`'${PROJECT_SLUG_PATTERN}'`],
      ],
      ["projects", "projects_slug_unique", "u", ["UNIQUE (slug)"]],
      [
        "specifications",
        "specifications_key_format_check",
        "c",
        [`'${SPECIFICATION_KEY_PATTERN}'`],
      ],
      ["specifications", "specifications_key_unique", "u", ["UNIQUE (key)"]],
      ["specifications", "specifications_pkey", "p", ["PRIMARY KEY (id)"]],
      [
        "specifications",
        "specifications_project_id_fkey",
        "f",
        ["FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE RESTRICT"],
      ],
      [
        "specifications",
        "specifications_status_check",
        "c",
        ["'draft'::text", "'in-review'::text", "'approved'::text"],
      ],
    ]);
    expect(s.indexes.map(([t, n, d]) => [t, n, d])).toEqual([
      ["projects", "projects_pkey", "USING btree (id)"],
      ["projects", "projects_slug_unique", "USING btree (slug)"],
      ["specifications", "specifications_key_unique", "USING btree (key)"],
      ["specifications", "specifications_pkey", "USING btree (id)"],
      [
        "specifications",
        "specifications_project_id_idx",
        "USING btree (project_id)",
      ],
      [
        "specifications",
        "specifications_updated_at_key_idx",
        "USING btree (updated_at DESC NULLS LAST, key)",
      ],
    ]);
  });

  test("after both: six tables in byte order, 48 columns, 18 constraints, 16 indexes", () => {
    const s = expectedStructure(2);
    expect(s.tables).toEqual([
      "accounts",
      "projects",
      "sessions",
      "specifications",
      "users",
      "verifications",
    ]);
    expect(s.columns).toHaveLength(48);
    expect(s.notNullColumns).toHaveLength(38);
    expect(s.constraints).toHaveLength(18);
    expect(s.indexes).toHaveLength(16);
    // Every auth constraint and index is compared exactly.
    for (const c of s.constraints.filter((c) =>
      APPROVED_MIGRATIONS[1]!.tables.includes(c[0]),
    )) {
      expect(c[4]).toBe("exact");
    }
    for (const x of s.indexes.filter((x) =>
      APPROVED_MIGRATIONS[1]!.tables.includes(x[0]),
    )) {
      expect(x[3]).toBe("exact");
    }
  });

  test.each([0, 3, 1.5, -1, Number.NaN])("refuses %s", (applied) => {
    expect(() => expectedStructure(applied)).toThrow(RangeError);
  });

  test("listNames", () => {
    expect(listNames(["a"])).toBe("a");
    expect(listNames(["a", "b"])).toBe("a and b");
    expect(listNames(["a", "b", "c"])).toBe("a, b, and c");
  });
});

describe("checkMigrationFiles", () => {
  test("accepts the approved files", () => {
    expect(judge(FILES)).toMatchObject({ ok: true, failed: [] });
    expect(judge(FILES).results).toHaveLength(8);
  });

  test("names extra and missing files without printing odd names", () => {
    const { failed } = judge({
      ...FILES,
      listing: [
        ...FILES.listing.filter((p) => p !== "meta/0001_snapshot.json"),
        "0002_next.sql",
        "x\u001b[31m.sql",
      ],
    });
    expect(failed[0]).toEqual({
      pass: false,
      label:
        "files: drizzle/ holds exactly the 2 approved migrations, their snapshots, and the journal",
      detail:
        "(extra: 0002_next.sql, extra: <10 characters>, missing: meta/0001_snapshot.json)",
    });
  });

  test("an unparseable journal fails", () => {
    const { failed } = judge({
      ...FILES,
      journal: { entries: [] },
    });
    expect(failed.map((r) => r.label)).toEqual([
      "files: the journal lists exactly 0000_initial_schema, 0001_auth_tables, in that order, with the reviewed timestamps",
    ]);
  });

  test("a journal with the wrong dialect fails", () => {
    expect(
      judge({ ...FILES, journal: { ...FILES.journal, dialect: "mysql" } }).ok,
    ).toBe(false);
  });
});

describe("readMigrationFiles on a copy of drizzle/", () => {
  let dir: string | undefined;
  afterEach(() => {
    if (dir) rmSync(dir, { recursive: true, force: true });
    dir = undefined;
  });
  const copy = () => {
    dir = mkdtempSync(join(tmpdir(), "ai-spec-studio-migrations-"));
    cpSync("drizzle", join(dir, "drizzle"), { recursive: true });
    return dir;
  };
  const failedLabels = (root: string) =>
    judge(readMigrationFiles(root)).failed.map((r) => r.label);

  test("an unchanged copy passes", () => {
    expect(failedLabels(copy())).toEqual([]);
  });

  test("a one-byte change to 0001's SQL fails its hash", () => {
    const root = copy();
    const path = join(root, "drizzle/0001_auth_tables.sql");
    writeFileSync(
      path,
      readFileSync(path, "utf8").replace("cascade", "CASCADE"),
    );
    expect(failedLabels(root)).toEqual([
      "files: 0001_auth_tables.sql matches the reviewed SHA-256",
    ]);
  });

  test("a deleted 0001 SQL file fails the listing and its hash", () => {
    const root = copy();
    rmSync(join(root, "drizzle/0001_auth_tables.sql"));
    expect(failedLabels(root)).toEqual([
      "files: drizzle/ holds exactly the 2 approved migrations, their snapshots, and the journal",
      "files: 0001_auth_tables.sql matches the reviewed SHA-256",
    ]);
  });

  test("an extra migration file fails the listing", () => {
    const root = copy();
    writeFileSync(join(root, "drizzle/0002_extra.sql"), "SELECT 1;");
    expect(failedLabels(root)).toEqual([
      "files: drizzle/ holds exactly the 2 approved migrations, their snapshots, and the journal",
    ]);
  });

  test("a symbolic link is listed, never followed", () => {
    const root = copy();
    symlinkSync("/etc/hosts", join(root, "drizzle/0002_link.sql"));
    const files = readMigrationFiles(root);
    expect(files.listing).toContain("0002_link.sql@");
    expect(files.sha256["0002_link.sql"]).toBeUndefined();
    expect(failedLabels(root)).toHaveLength(1);
  });

  test("a nested directory is listed, not descended into", () => {
    const root = copy();
    mkdirSync(join(root, "drizzle/extra"));
    writeFileSync(join(root, "drizzle/extra/0002.sql"), "SELECT 1;");
    const files = readMigrationFiles(root);
    expect(files.listing).toContain("extra/");
    expect(files.listing).not.toContain("extra/0002.sql");
    expect(failedLabels(root)).toHaveLength(1);
  });

  test("swapped journal entries fail the order checks", () => {
    const root = copy();
    const path = join(root, "drizzle/meta/_journal.json");
    const journal = JSON.parse(readFileSync(path, "utf8")) as {
      entries: unknown[];
    };
    journal.entries.reverse();
    writeFileSync(path, JSON.stringify(journal));
    expect(failedLabels(root)).toEqual([
      "files: the journal lists exactly 0000_initial_schema, 0001_auth_tables, in that order, with the reviewed timestamps",
      "files: journal timestamps strictly increase (the migrator relies on it)",
    ]);
  });

  test("a journal that isn't JSON fails", () => {
    const root = copy();
    writeFileSync(join(root, "drizzle/meta/_journal.json"), "{not json");
    expect(failedLabels(root)).toContain(
      "files: the journal lists exactly 0000_initial_schema, 0001_auth_tables, in that order, with the reviewed timestamps",
    );
  });

  test("a snapshot pointing at the wrong parent fails its hash and the chain", () => {
    const root = copy();
    const path = join(root, "drizzle/meta/0001_snapshot.json");
    const snapshot = JSON.parse(readFileSync(path, "utf8")) as {
      prevId: string;
    };
    snapshot.prevId = FIRST_SNAPSHOT_PREV_ID;
    writeFileSync(path, JSON.stringify(snapshot, null, 2));
    expect(failedLabels(root)).toEqual([
      "files: meta/0001_snapshot.json matches the reviewed SHA-256",
      "files: the snapshots form one chain (each prevId is the previous snapshot's id)",
    ]);
  });
});
