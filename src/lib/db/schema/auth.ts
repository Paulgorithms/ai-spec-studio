import { sql } from "drizzle-orm";
import {
  boolean,
  check,
  foreignKey,
  index,
  pgTable,
  text,
  unique,
  uuid,
} from "drizzle-orm/pg-core";
import { timestampColumn, timestamps } from "./columns";

// Authentication tables for Better Auth 1.7.27 (GitHub and Google OAuth,
// database sessions). Better Auth reaches them through an explicit mapping
// from its singular model names (user, session, account, verification) in
// src/lib/auth/server.ts.
//
// Better Auth's schema check compares the property names below (its field
// names), nullability, and defaults, so keep them exactly as they are. SQL
// names, types, and extra constraints are ours.
//
// Primary keys are generated by PostgreSQL: with generateId "uuid", the
// Drizzle adapter sends no id and reads it back with RETURNING. Better Auth
// sometimes supplies its own (version 5) UUID for single-use records, which
// the uuid column accepts.

// A person who signed in with GitHub or Google. Better Auth lowercases
// email before writing it.
export const users = pgTable(
  "users",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    name: text("name").notNull(),
    email: text("email").notNull(),
    emailVerified: boolean("email_verified").notNull().default(false),
    image: text("image"),
    ...timestamps(),
  },
  (table) => [unique("users_email_unique").on(table.email)],
);

// A signed-in browser session. `token` is the session cookie's value
// (before signing), so anyone who can read this table can use a session.
// ip_address is always NULL: the app doesn't store client IP addresses.
export const sessions = pgTable(
  "sessions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    expiresAt: timestampColumn("expires_at").notNull(),
    token: text("token").notNull(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: uuid("user_id").notNull(),
    ...timestamps(),
  },
  (table) => [
    foreignKey({
      name: "sessions_user_id_fkey",
      columns: [table.userId],
      foreignColumns: [users.id],
    }).onDelete("cascade"),
    unique("sessions_token_unique").on(table.token),
    index("sessions_user_id_idx").on(table.userId),
  ],
);

// A user's identity at an OAuth provider. Provider tokens are encrypted by
// Better Auth (encryptOAuthTokens) before they reach these columns.
export const accounts = pgTable(
  "accounts",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: uuid("user_id").notNull(),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: timestampColumn("access_token_expires_at"),
    refreshTokenExpiresAt: timestampColumn("refresh_token_expires_at"),
    scope: text("scope"),
    // Required by Better Auth's schema, but email and password sign-in is
    // disabled, so it must always be NULL.
    password: text("password"),
    ...timestamps(),
  },
  (table) => [
    foreignKey({
      name: "accounts_user_id_fkey",
      columns: [table.userId],
      foreignColumns: [users.id],
    }).onDelete("cascade"),
    // One app account per provider identity. Better Auth doesn't declare
    // this; it keeps concurrent sign-ins from duplicating an identity.
    unique("accounts_provider_id_account_id_unique").on(
      table.providerId,
      table.accountId,
    ),
    index("accounts_user_id_idx").on(table.userId),
    check("accounts_password_null_check", sql`${table.password} IS NULL`),
  ],
);

// Short-lived values, such as OAuth state between sign-in and callback.
export const verifications = pgTable(
  "verifications",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: timestampColumn("expires_at").notNull(),
    ...timestamps(),
  },
  (table) => [index("verifications_identifier_idx").on(table.identifier)],
);

export type UserRow = typeof users.$inferSelect;
export type SessionRow = typeof sessions.$inferSelect;
export type AccountRow = typeof accounts.$inferSelect;
export type VerificationRow = typeof verifications.$inferSelect;
